#!/usr/bin/env python3
"""Generate internal/worldgen/flammable_gen.go — the fire flammability table.

Each block state's ignite odds (the chance it catches from a neighbouring
fire) and burn odds (the chance an adjacent fire consumes it), asked of the
running game (scripts/extract): FireBlock's own getIgniteOdds/getBurnOdds,
so its setFlammable table and its per-state rule — a waterlogged state never
burns — both come with it. This replaced a transcribed copy of the table
that had fallen behind (the 1.21.11 shelves were missing).

Runs of consecutive states with the same odds are merged; states that never
burn are left out, as the lookup's miss is 0.

    python3 scripts/gen_flammable.py     # canonical version: canon.py
"""
import json
import os

import canon

OUT = os.path.join(os.path.dirname(__file__), "..", "internal", "worldgen", "flammable_gen.go")


def main():
    rows = []  # [lo, hi, ignite, burn, name]
    for b in sorted(json.load(open(canon.extract()))["blocks"], key=lambda b: b["minStateId"]):
        for i, (ig, bu) in enumerate(zip(b["igniteOdds"], b["burnOdds"])):
            s = b["minStateId"] + i
            if (ig, bu) == (0, 0):
                continue
            if rows and rows[-1][1] + 1 == s and rows[-1][2:4] == [ig, bu] and rows[-1][4] == b["name"]:
                rows[-1][1] = s
            else:
                rows.append([s, s, ig, bu, b["name"]])
    with open(OUT, "w") as f:
        f.write("// Code generated by scripts/gen_flammable.py. DO NOT EDIT.\n")
        f.write("// Fire flammability (ignite/burn odds) of each block state, as vanilla's\n")
        f.write("// FireBlock answers it (canonical %s).\n\n" % canon.VERSION)
        f.write("package worldgen\n\n")
        f.write("// flammable is one contiguous block-state id range with its fire odds.\n")
        f.write("type flammable struct{ lo, hi, ignite, burn uint32 }\n\n")
        f.write("// flammableRanges is sorted by lo for binary search (see Flammability).\n")
        f.write("var flammableRanges = []flammable{\n")
        for lo, hi, ig, bu, name in rows:
            f.write(f"\t{{{lo}, {hi}, {ig}, {bu}}}, // {name}\n")
        f.write("}\n\n")
        f.write("""// Flammability returns a block state's fire ignite odds (chance the block
// catches from a neighbouring fire) and burn odds (chance an adjacent fire
// consumes it), both 0 for non-flammable blocks. Mirrors FireBlock's
// getIgniteOdds/getBurnOdds.
func Flammability(state uint32) (ignite, burn uint32) {
	lo, hi := 0, len(flammableRanges)-1
	for lo <= hi {
		mid := (lo + hi) / 2
		r := flammableRanges[mid]
		switch {
		case state < r.lo:
			hi = mid - 1
		case state > r.hi:
			lo = mid + 1
		default:
			return r.ignite, r.burn
		}
	}
	return 0, 0
}
""")
    print(f"wrote {len(rows)} ranges to {os.path.normpath(OUT)}")


if __name__ == "__main__":
    main()
